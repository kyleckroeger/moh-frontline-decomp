#!/usr/bin/env python3
"""gen_axdsp.py <out.cpp>: write research/data/init/axDspSlave.cpp from the original ELF
(the AX DSP microcode as 16-bit words, and its byte length)."""
import sys, struct; sys.path.insert(0,'tools')
from formats import Elf32
e=Elf32(open('orig/GMFE69/Moh2RelGC.elf','rb').read())
sec=[s for s in e.sections if s['name']=='.data'][0]
o=0x8018e2a0-sec['address']; b=e.contents(sec)[o:o+6624]
w=struct.unpack('>3312H',b)
out=['''// axDspSlave / axDspSlaveLength: the AX library's DSP microcode, which AXOut hands to the
// DSP (DSPAddTask) at AXInit, and its length in bytes (0x19e0). Transcribed as data from the
// original image (maintainer decision 2026-11-13, docs/Remaining.md): it is DSP machine code,
// not something this project reconstructs, and the PC port replaces it (PortReadiness step
// 2.2). The file name is this project's; no file record names the original's. In the
// original, axDspSlave follows __AXMixCycles in .data and axDspSlaveLength follows
// CmdCalibrate in .sdata. Generated by research/tools/gen_axdsp.py (the original's big-endian
// 16-bit words, 8 per line). Checked by research/tools/check_data.py.
// settings: config/GMFE69/AXOut.json

extern unsigned short axDspSlave[3312];
extern unsigned short axDspSlaveLength;

unsigned short axDspSlave[3312] = {''']
for i in range(0,3312,8):
    out.append('    '+', '.join('0x%04x'%x for x in w[i:i+8])+',')
out.append('};\n\nunsigned short axDspSlaveLength = sizeof(axDspSlave);\n')
open(sys.argv[1],'w').write('\n'.join(out))
