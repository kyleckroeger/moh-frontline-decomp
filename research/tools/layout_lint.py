#!/usr/bin/env python3
"""layout_lint.py: do all the files that declare a class agree on its layout?

Most game units and drafts declare their own partial view of each class they touch
(CVector3 in 256 files, ISceneNode in 170). A view that puts a field at the wrong offset
still compiles, and still runs until it reads the wrong word. Every gameplay draft bug
found in Dolphin on 2026-11-09 was one of these: BSGO_Basic's vtable pointer,
CCompartment's light pool, BSGO_Soldier::m_node, CScene::m_exclusions.

This compiles every game unit and every draft with `-sym on` (code is unchanged; see
dw.py), reads each struct/class layout from the DWARF 1 debug section, and compares the
views of each class by name:

    member   the same member name at different offsets (or bit positions)
    vptr     the vtable pointer at different offsets
    base     the same base class at different offsets
    width    scalar members (numbers, pointers) at the same offset with different sizes;
             a scalar laid over an array or a struct is a normal partial view, not counted

Placeholder names (unknownXX, padXX, ...) are not compared by name, since every view
uses them for whatever it doesn't know.

    layout_lint.py [--jobs N] [--only SUBSTR]    write research/layout/*.tsv
    layout_lint.py --class NAME                  print every view of one class
    layout_lint.py --check FILE SETTINGS.json    lint one file against the stored views

Outputs (research/layout/, committed):
    conflicts.tsv   one row per conflict: class, kind, key, then each variant with the
                    files that hold it (matched source first)
    classes.tsv     per class: views, sizes seen, members every view agrees on
and build/layout/views.json, the raw layouts (for --class, --check and --reuse; not
committed, so run a full lint first).

Matched code (src/) proves the offsets it uses, so the column to read first is
draft_only: a draft holding a variant that no matched file holds. That is a lead, not a
verdict. On 2026-11-10 the 23 such leads outside multiplayer were all names reused for different fields (a BSP
leaf's waypoint list called "triggers"), not bugs. Two matched files disagreeing on a
name is a step-3 header problem, not a code bug: both are byte-exact.

Validated on the drafts before the 2026-11-09 fixes: it flags the old SweepAllExtents
(m_exclusions +0x108 against +0x118 in three matched files) and the old
CreateCollisionVolume (BSGO_Basic's vtable pointer at +0 against +0xc in 62 views). The
old BSGO_Soldier and LightPool views only conflict with their own fixed copies, since no
matched file names those classes the same way, so the lint can't see every layout bug.
"""
import argparse, collections, csv, glob, json, os, re, struct, subprocess, sys, tempfile
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
OUT = ROOT / "research/layout"
VIEWS = ROOT / "build/layout/views.json"  # 1.7 MB, regenerated by every full run

PLACEHOLDER = re.compile(r"^(_*(unknown|unk|pad|padding|gap|field|reserved|dummy|filler|skip|rest|tail|data_|u)_?[0-9a-fA-Fx]*|_[0-9a-fA-Fx]+|m_unknown[0-9a-fA-Fx]*|m_pad[0-9a-fA-Fx]*|m_unk[0-9a-fA-Fx]*)$", re.I)

# DWARF 1 fundamental type sizes (FT_*)
FT_SIZE = {0x1: 1, 0x2: 1, 0x3: 1, 0x4: 2, 0x5: 2, 0x6: 2, 0x7: 4, 0x8: 4, 0x9: 4, 0xa: 4, 0xb: 4,
           0xc: 4, 0xd: 4, 0xe: 4, 0xf: 8, 0x10: 8, 0x14: 0, 0x15: 1, 0x18: 1, 0x8008: 8, 0x8208: 8}
FT_NAME = {0x1: "char", 0x2: "schar", 0x3: "uchar", 0x4: "short", 0x5: "short", 0x6: "ushort",
           0x7: "int", 0x8: "int", 0x9: "uint", 0xa: "long", 0xb: "long", 0xc: "ulong",
           0xd: "void*", 0xe: "float", 0xf: "double", 0x10: "ldouble", 0x14: "void", 0x15: "bool",
           0x18: "bool", 0x8008: "llong", 0x8208: "ullong"}
CLASS_TAGS = {0x02: "class", 0x13: "struct", 0x17: "union"}
MEMBER, INHERIT, ARRAY, ENUM, TYPEDEF, PTR_TO_MEMBER = 0x0d, 0x1c, 0x01, 0x04, 0x16, 0x1f


# ---------------------------------------------------------------- DWARF 1 reading

def sections(b):
    shoff = struct.unpack(">I", b[32:36])[0]
    n, si = struct.unpack(">HH", b[48:52])
    sh = [struct.unpack(">10I", b[shoff + i * 40:shoff + i * 40 + 40]) for i in range(n)]
    names = b[sh[si][4]:sh[si][4] + sh[si][5]]
    return [(names[s[0]:names.index(b"\0", s[0])].decode(), s) for s in sh]


def debug_bytes(path):
    """The .debug section with its relocations applied (references become offsets)."""
    b = open(path, "rb").read()
    secs = sections(b)
    idx = {name: i for i, (name, _) in enumerate(secs)}
    if ".debug" not in idx:
        return None
    dbg_i = idx[".debug"]
    _, s = secs[dbg_i]
    d = bytearray(b[s[4]:s[4] + s[5]])
    symtab = next((s for name, s in secs if s[1] == 2), None)
    for name, rs in secs:
        if rs[1] == 4 and rs[7] == dbg_i:  # SHT_RELA applying to .debug
            for off in range(rs[4], rs[4] + rs[5], 12):
                where, info, addend = struct.unpack(">IIi", b[off:off + 12])
                sym = info >> 8
                st = symtab[4] + sym * 16
                _, value, _, _, _, shndx = struct.unpack(">IIIBBH", b[st:st + 16])
                if shndx == dbg_i and where + 4 <= len(d):
                    struct.pack_into(">I", d, where, (value + addend) & 0xFFFFFFFF)
    return bytes(d)


def entries(d):
    """{offset: (tag, attrs, end)} for every DWARF 1 entry."""
    out, i = {}, 0
    while i + 4 <= len(d):
        ln = struct.unpack(">I", d[i:i + 4])[0]
        if ln < 8:
            out[i] = (None, {}, i + max(ln, 4)); i += max(ln, 4); continue
        tag = struct.unpack(">H", d[i + 4:i + 6])[0]
        a, j, e = {}, i + 6, i + ln
        while j < e:
            at = struct.unpack(">H", d[j:j + 2])[0]; j += 2; f = at & 15
            if f in (1, 2): v = struct.unpack(">I", d[j:j + 4])[0]; j += 4
            elif f == 3: n = struct.unpack(">H", d[j:j + 2])[0]; v = d[j + 2:j + 2 + n]; j += 2 + n
            elif f == 4: n = struct.unpack(">I", d[j:j + 4])[0]; v = d[j + 4:j + 4 + n]; j += 4 + n
            elif f == 5: v = struct.unpack(">H", d[j:j + 2])[0]; j += 2
            elif f == 6: v = struct.unpack(">I", d[j:j + 4])[0]; j += 4
            elif f == 7: v = struct.unpack(">Q", d[j:j + 8])[0]; j += 8
            elif f == 8: k = d.index(b"\0", j); v = d[j:k].decode("latin1"); j = k + 1
            else: break
            a[at] = v
        out[i] = (tag, a, e); i = e
    return out


def location_offset(block):
    """OP_CONST n, OP_ADD -> n (member locations)."""
    if isinstance(block, bytes) and len(block) >= 5 and block[0] == 4:
        return struct.unpack(">I", block[1:5])[0]
    return None


class Types:
    def __init__(self, es):
        self.es = es

    def size(self, attrs, depth=0):
        if depth > 20:
            return None
        if 0x55 in attrs:
            return FT_SIZE.get(attrs[0x55])
        for at in (0x63, 0x83):  # mod_fund_type / mod_u_d_type
            if at in attrs:
                mods = attrs[at][:-2] if at == 0x63 else attrs[at][:-4]
                if any(m in (1, 2) for m in mods):
                    return 4
                if at == 0x63:
                    return FT_SIZE.get(struct.unpack(">H", attrs[at][-2:])[0])
                return self.ref_size(struct.unpack(">I", attrs[at][-4:])[0], depth + 1)
        if 0x72 in attrs:
            return self.ref_size(attrs[0x72], depth + 1)
        return None

    def ref_size(self, off, depth):
        e = self.es.get(off)
        if not e or e[0] is None:
            return None
        tag, a, _ = e
        if 0xb6 in a:
            return a[0xb6]
        if tag == TYPEDEF:
            return self.size(a, depth)
        if tag == ARRAY:
            return self.array_size(a, depth)
        if tag == PTR_TO_MEMBER:
            return 4
        return None

    def array_size(self, a, depth):
        sub = a.get(0xa3)
        if not isinstance(sub, bytes):
            return None
        i, count, elem = 0, 1, None
        try:
            while i < len(sub):
                fmt = sub[i]; i += 1
                if fmt == 0:  # FMT_FT_C_C: index fund type, low, high
                    i += 2
                    lo, hi = struct.unpack(">ii", sub[i:i + 8]); i += 8
                    count *= hi - lo + 1
                elif fmt == 8:  # FMT_ET: element type attribute
                    at = struct.unpack(">H", sub[i:i + 2])[0]; i += 2; f = at & 15
                    if f == 5: v = struct.unpack(">H", sub[i:i + 2])[0]; i += 2
                    elif f in (2, 6): v = struct.unpack(">I", sub[i:i + 4])[0]; i += 4
                    elif f == 3: n = struct.unpack(">H", sub[i:i + 2])[0]; v = sub[i + 2:i + 2 + n]; i += 2 + n
                    else: return None
                    elem = self.size({at: v}, depth + 1)
                    break
                else:
                    return None
        except struct.error:
            return None
        return None if elem is None else count * elem

    def describe(self, attrs, depth=0):
        if depth > 8:
            return "?"
        if 0x55 in attrs:
            return FT_NAME.get(attrs[0x55], "ft%x" % attrs[0x55])
        for at in (0x63, 0x83):
            if at in attrs:
                raw = attrs[at]
                mods = raw[:-2] if at == 0x63 else raw[:-4]
                base = (FT_NAME.get(struct.unpack(">H", raw[-2:])[0], "?") if at == 0x63
                        else self.ref_name(struct.unpack(">I", raw[-4:])[0], depth + 1))
                return base + "".join({1: "*", 2: "&", 3: " const", 4: " volatile"}.get(m, "") for m in reversed(mods))
        if 0x72 in attrs:
            return self.ref_name(attrs[0x72], depth + 1)
        return "?"

    def ref_name(self, off, depth):
        e = self.es.get(off)
        if not e or e[0] is None:
            return "?"
        tag, a, _ = e
        if tag == ARRAY:
            n = self.array_size(a, depth)
            return "array[%s]" % ("?" if n is None else hex(n))
        return a.get(0x38) or {ENUM: "enum", PTR_TO_MEMBER: "ptm"}.get(tag, "?")


def layouts(d):
    """[{name, kind, size, members:[(name, off, bitoff, bitsize, size, type)], bases:[(name, off)]}]"""
    es = entries(d)
    ty = Types(es)
    out = []
    for off, (tag, a, end) in es.items():
        if tag not in CLASS_TAGS or not a.get(0x38) or 0xb6 not in a:
            continue  # anonymous, or a declaration only
        stop = a.get(0x12) or end
        members, bases = [], []
        p = end
        while p < stop and p in es:
            t, ma, e = es[p]
            if t == MEMBER and 0x38 in ma:
                mo = location_offset(ma.get(0x23))
                if mo is not None:
                    members.append((ma[0x38], mo, ma.get(0xc5), ma.get(0xd6), ty.size(ma), ty.describe(ma)))
            elif t == INHERIT:
                bo = location_offset(ma.get(0x23))
                bases.append((ty.describe(ma), bo))
            nxt = ma.get(0x12) if t is not None else None
            p = nxt if nxt and nxt > p else e
        out.append(dict(name=a[0x38], kind=CLASS_TAGS[tag], size=a[0xb6], members=members, bases=bases))
    return out


# ---------------------------------------------------------------- compiling

def compile_sym(job):
    label, settings, path = job
    from setup_compiler import setup_compiler
    t = json.load(open(ROOT / settings))
    compiler, wrapper = setup_compiler(t["compiler_version"], "GC")
    src = ROOT / path
    # As in link_drafts.py, a few .c drafts only compile as C++.
    suffixes = [src.suffix] + ([".cpp"] if src.suffix == ".c" and path.startswith("research/") else [])
    with tempfile.TemporaryDirectory() as work:
        for suffix in suffixes:
            probe = Path(work) / ("probe" + suffix)
            probe.write_text(src.read_text(errors="replace"))
            cmd = [str(wrapper), str(compiler / "mwcceppc.exe"), "-c", *t["compiler_flags"], "-sym", "on", "-I-",
                   f"-I{src.parent}", *[f"-I{ROOT / p}" for p in t.get("include_dirs", [])], str(probe), "-o", "probe.o"]
            for _ in range(3):  # wibo occasionally fails under parallel load
                r = subprocess.run(cmd, cwd=work, capture_output=True, text=True)
                if r.returncode == 0 and (Path(work) / "probe.o").exists():
                    d = debug_bytes(Path(work) / "probe.o")
                    return label, (layouts(d) if d else []), ""
                if "Error" in r.stdout + r.stderr:
                    break  # a real compile error: retrying won't help
        return label, None, (r.stdout + r.stderr)[-300:]


def jobs(only):
    out = []
    for f in sorted(glob.glob(str(ROOT / "config/GMFE69/*.json"))):
        t = json.load(open(f))
        if t.get("category") != "reconstructed_game" or "source" not in t:
            continue
        out.append((t["source"], os.path.relpath(f, ROOT), t["source"]))
    for row in csv.DictReader(open(ROOT / "research/drafts/index.tsv"), delimiter="\t"):
        out.append((row["draft"], row["compile_settings_from"], row["draft"]))
    return [j for j in out if not only or only in j[0]]


# ---------------------------------------------------------------- comparing

SCALARS = set(FT_NAME.values())


def scalar(ty):
    return ty in SCALARS or ty.endswith(("*", "&", " const", " volatile")) or ty == "enum"


def matched(label):
    return label.startswith("src/")



def fmt_files(files):
    files = sorted(set(files), key=lambda f: (not matched(f), f))
    return f"{len(files)}: " + ", ".join(files[:6]) + (" ..." if len(files) > 6 else "")


def compare(views):
    """views: {class: [(file, layout)]} -> conflicts, summary rows"""
    conflicts, summary = [], []
    for cls in sorted(views):
        if cls.startswith("@"):
            continue  # unnamed structs: CW names them after the compiled file
        vs = views[cls]
        by_member = collections.defaultdict(lambda: collections.defaultdict(list))
        by_vptr = collections.defaultdict(list)
        by_base = collections.defaultdict(lambda: collections.defaultdict(list))
        by_off = collections.defaultdict(lambda: collections.defaultdict(list))
        for f, lay in vs:
            for n, off, bo, bs, size, ty in lay["members"]:
                if n == "__vptr$":
                    by_vptr[off].append(f); continue
                if PLACEHOLDER.match(n):
                    continue
                key = (off, bo, bs)
                by_member[n][key].append(f)
                if bo is None and size and scalar(ty):
                    by_off[off][size].append((f, n))
            for b, off in lay["bases"]:
                by_base[b][off].append(f)
        for n, variants in sorted(by_member.items()):
            if len(variants) > 1:
                conflicts.append((cls, "member", n, [("+%#x" % k[0] + ("" if k[1] is None else " bit%d:%d" % (k[1], k[2])), fs)
                                                      for k, fs in sorted(variants.items(), key=lambda kv: -len(kv[1]))]))
        if len(by_vptr) > 1:
            conflicts.append((cls, "vptr", "__vptr$", [("+%#x" % k, fs) for k, fs in sorted(by_vptr.items(), key=lambda kv: -len(kv[1]))]))
        for b, variants in sorted(by_base.items()):
            if len(variants) > 1:
                conflicts.append((cls, "base", b, [("+%#x" % k, fs) for k, fs in sorted(variants.items(), key=lambda kv: -len(kv[1]))]))
        for off, sizes in sorted(by_off.items()):
            if len(sizes) > 1:
                conflicts.append((cls, "width", "+%#x" % off,
                                  [("%d bytes (%s)" % (s, "/".join(sorted({n for _, n in fs}))[:60]), [f for f, _ in fs])
                                   for s, fs in sorted(sizes.items(), key=lambda kv: -len(kv[1]))]))
        sizes = collections.Counter(lay["size"] for _, lay in vs)
        agreed = [n for n, v in sorted(by_member.items(), key=lambda kv: min(k[0] for k in kv[1])) if len(v) == 1]
        summary.append((cls, len(vs), sum(matched(f) for f, _ in vs),
                        " ".join("%#x×%d" % (s, c) for s, c in sorted(sizes.items())),
                        " ".join("%s@%#x" % (n, next(iter(by_member[n]))[0]) for n in agreed)))
    return conflicts, summary


def draft_only(c):
    """Draft files holding a variant that no matched file holds, when matched files hold another."""
    variants = c[3]
    if not any(matched(f) for _, fs in variants for f in fs):
        return []
    return sorted({f for _, fs in variants if not any(matched(x) for x in fs) for f in fs})


def severity(c):
    """Sort key: conflicts with a draft against matched source first, then by kind."""
    cls, kind, key, variants = c
    drafty = any(not matched(f) for _, fs in variants for f in fs)
    has_src = any(matched(f) for _, fs in variants for f in fs)
    return ({"vptr": 0, "base": 1, "member": 2, "width": 3}[kind], not draft_only(c), not (drafty and has_src), cls, key)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--jobs", type=int, default=4)
    ap.add_argument("--only")
    ap.add_argument("--class", dest="cls")
    ap.add_argument("--check", nargs=2, metavar=("FILE", "SETTINGS"))
    ap.add_argument("--reuse", action="store_true", help="compare the stored views.json again without compiling")
    a = ap.parse_args()
    if a.check:
        path, settings = a.check
        _, lays, err = compile_sym(("check", settings, os.path.relpath(Path(path).resolve(), ROOT)))
        if lays is None:
            raise SystemExit("does not compile: " + err)
        data = json.load(open(VIEWS))
        label = "CHECKED:" + path
        views = collections.defaultdict(list)
        mine = {lay["name"] for lay in lays}
        for f, ls in data["views"].items():
            if os.path.abspath(ROOT / f) == os.path.abspath(path):
                continue  # the stored copy of the same file
            for lay in ls:
                if lay["name"] in mine:
                    views[lay["name"]].append((f, lay))
        for lay in lays:
            views[lay["name"]].append((label, lay))
        conflicts, _ = compare(views)
        n = 0
        for cls, kind, key, variants in sorted(conflicts, key=severity):
            if any(label in fs for _, fs in variants) and not cls.startswith("@"):
                n += 1
                print(f"{cls} {kind} {key}:")
                for v, fs in variants:
                    print(f"    {'>>' if label in fs else '  '} {v:24} {fmt_files([f for f in fs if f != label]) if label not in fs or len(fs) > 1 else 'this file'}")
        print(f"{n} conflicts involving {path}")
        return
    if a.cls:
        data = json.load(open(VIEWS))
        for f, lays in sorted(data["views"].items(), key=lambda kv: (not matched(kv[0]), kv[0])):
            for lay in lays:
                if lay["name"] == a.cls:
                    print(f"{f}  size {lay['size']:#x}  bases {lay['bases']}")
                    for n, off, bo, bs, size, ty in lay["members"]:
                        print(f"    +{off:#06x}{'' if bo is None else f' bit{bo}:{bs}'}  {n:28} {ty} ({size})")
        return
    js = [] if a.reuse else jobs(a.only)
    results, failed = {}, {}
    if a.reuse:
        stored = json.load(open(VIEWS))
        results, failed = stored["views"], stored["failed"]
    with ProcessPoolExecutor(a.jobs) as ex:
        for i, (label, lays, err) in enumerate(ex.map(compile_sym, js, chunksize=4)):
            if lays is None:
                failed[label] = err
            else:
                results[label] = lays
            if i % 100 == 0:
                print(f"{i}/{len(js)}", file=sys.stderr, flush=True)
    views = collections.defaultdict(list)
    for f, lays in results.items():
        seen = set()
        for lay in lays:
            # A unit can carry one class twice (a header view and a local one); keep both
            # only if they differ.
            key = (lay["name"], json.dumps(lay["members"]))
            if key not in seen:
                seen.add(key); views[lay["name"]].append((f, lay))
    conflicts, summary = compare(views)
    conflicts.sort(key=severity)
    OUT.mkdir(exist_ok=True)
    if not a.only and not a.reuse:
        VIEWS.parent.mkdir(parents=True, exist_ok=True)
        json.dump(dict(views=results, failed=failed), open(VIEWS, "w"), separators=(",", ":"))
    if not a.only:
        with open(OUT / "conflicts.tsv", "w") as o:
            o.write("class\tkind\tkey\tdraft_only\tvariants\n")
            for c in conflicts:
                cls, kind, key, variants = c
                o.write(f"{cls}\t{kind}\t{key}\t{' '.join(Path(f).name for f in draft_only(c))}\t" +
                        " | ".join(f"{v} [{fmt_files(fs)}]" for v, fs in variants) + "\n")
        with open(OUT / "classes.tsv", "w") as o:
            o.write("class\tviews\tmatched_views\tsizes\tagreed_members\n")
            for row in summary:
                o.write("\t".join(map(str, row)) + "\n")
    kinds = collections.Counter(c[1] for c in conflicts)
    dvs = sum(1 for c in conflicts if draft_only(c))
    print(f"{len(results)} files compiled, {len(failed)} failed; {len(views)} classes; "
          f"{len(conflicts)} conflicts {dict(kinds)}; {dvs} where a draft has a layout no matched file has")
    for f, e in list(failed.items())[:10]:
        print("  failed:", f, e.strip().splitlines()[-1:] if e.strip() else "")
    if a.only:
        for c in conflicts:
            print(c[0], c[1], c[2], [(v, fs) for v, fs in c[3]])


if __name__ == "__main__":
    main()
